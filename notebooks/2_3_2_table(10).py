import pandas as pd

# Загрузка нашего датасета временного ряда
df = pd.read_csv("tuv_nel_data.csv")

# ==========================================
# ЭТАП 3: Статистический анализ
# ==========================================
# Расчет основных описательных статистик для числовых параметров
stats = df[["mass_flow_raw", "density", "GVF", "WC", "mass_flow_true"]].describe().T

print("=" * 70)
print("СТАТИСТИЧЕСКИЙ АНАЛИЗ ПАРАМЕТРОВ ВРЕМЕННОГО РЯДА")
print("=" * 70)
# Выводим среднее, стандартное отклонение, минимум, медиану (50%) и максимум
print(stats[["mean", "std", "min", "50%", "max"]])
print("=" * 70)

# ==========================================
# ЭТАП 4: Анализ пропусков
# ==========================================
print("\n" + "=" * 70)
print("ПРОВЕРКА НАЛИЧИЯ ПРОПУСКОВ")
print("=" * 70)
for col in df.columns:
    missing = df[col].isnull().sum()
    print(f"Признак {col:<15} | Пропусков: {missing} ({(missing/len(df))*100:.2f}%)")
print("=" * 70)
