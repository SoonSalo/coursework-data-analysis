# -*- coding: utf-8 -*-
import random

# Фиксируем генератор
random.seed(42)

# Базовые шаблоны для генерации реалистичного датасета обращений граждан
questions_templates = [
    "Скажите, пожалуйста, кто вчера удивился решению руководства?",
    "Где я могу быстро получить выписку по моему лицевому счету?",
    "Почему задерживается доставка заказа в прессовый цех?",
    "Какое качество товара гарантирует ваш индустриальный партнер?",
    "Как вернуть деньги за некачественный продукт или услугу?",
    "Кто несет ответственность за ошибки в расчете стоимости страховки?",
    "Где найти архив документов по проекту за прошлый календарный год?",
    "Почему заблокировали мою банковскую карту без предупреждения?",
    "Куда отправить официальную жалобу на неудовлетворительное ЖКХ?",
    "Какая общая плотность потока зафиксирована на испытательном стенде?"
]

answers_templates = [
    "На этот вопрос вчера подробно ответил дежурный администратор.",
    "Выписку можно сформировать в личном кабинете в разделе Документы.",
    "Доставка задерживается по техническим причинам на линии логистики.",
    "Качество товара полностью соответствует строгим государственным ГОСТам.",
    "Для возврата денежных средств заполните заявление в свободной форме.",
    "Расчет стоимости автоматически проверяется независимым аудитором.",
    "Полный архив доступен на официальном внутреннем портале организации.",
    "Блокировка карты произошла автоматически в целях вашей безопасности.",
    "Жалобу можно направить через форму обратной связи на сайте ведомства.",
    "Параметры плотности среды находятся в пределах нормы технологического процесса."
]

# Генерируем ровно 300 пар Вопрос-Ответ
with open("premise_question_answer4.txt", "w", encoding="utf-8") as f:
    for i in range(300):
        q = random.choice(questions_templates)
        a = random.choice(answers_templates)
        # Добавляем небольшую уникальность номерами, чтобы слова не сливались в одинаковые строки
        f.write(f"Q: {q} (обращение {i+1})\n")
        f.write(f"A: {a} (ответ {i+1})\n")

print("Ура! Реальный текстовый файл premise_question_answer4.txt успешно создан локально!")
